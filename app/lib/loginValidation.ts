// Общая проверка для самостоятельной и административной смены логина.
// Регистр сохраняется: вход и создание сотрудников уже различают строчные и прописные буквы.
export const getLoginValidationError = (login: string): string | null => {
    if (!login) {
        return 'Укажите новый логин';
    }

    if (login.length > 120) {
        return 'Логин должен содержать не более 120 символов';
    }

    if (/[\s\u0000-\u001f\u007f]/u.test(login)) {
        return 'Логин не должен содержать пробелы или управляющие символы';
    }

    return null;
};
